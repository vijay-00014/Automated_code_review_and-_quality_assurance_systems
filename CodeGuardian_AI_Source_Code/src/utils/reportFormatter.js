/**
 * Report Exporter Helper
 * Formats code review results into downloadable Markdown or JSON files.
 */

export function exportReviewReport(reviewData, filename = 'code-review-report', format = 'markdown') {
  if (!reviewData) return;

  let content = '';
  let mimeType = 'text/plain';
  let extension = 'txt';

  if (format === 'json') {
    content = JSON.stringify(reviewData, null, 2);
    mimeType = 'application/json';
    extension = 'json';
  } else {
    extension = 'md';
    mimeType = 'text/markdown';
    content = `# 🛡️ Automated Code Review Report

**Date:** ${new Date(reviewData.timestamp || Date.now()).toLocaleString()}
**Overall Score:** ${reviewData.overallScore}/100 (Grade ${reviewData.grade})
**Summary:** ${reviewData.summaryText}

---

## 📊 Metrics Overview

| Metric | Score / Value |
| :--- | :--- |
| **Security Rating** | ${reviewData.metrics?.securityScore || 0}/100 |
| **Performance Rating** | ${reviewData.metrics?.performanceScore || 0}/100 |
| **Maintainability Index** | ${reviewData.metrics?.maintainabilityScore || 0}/100 |
| **Algorithmic Complexity** | ${reviewData.metrics?.complexityRating || 'N/A'} |
| **Testability Score** | ${reviewData.metrics?.testabilityScore || 0}/100 |

### 🐞 Issue Counts
- 🔴 **Critical Severity:** ${reviewData.counts?.critical || 0}
- 🟠 **Major Severity:** ${reviewData.counts?.major || 0}
- 🟡 **Minor Severity:** ${reviewData.counts?.minor || 0}
- 🔵 **Info / Style:** ${reviewData.counts?.info || 0}

---

## 🔍 Detailed Line-by-Line Findings

${(reviewData.issues || []).map((issue, idx) => `
### ${idx + 1}. [Line ${issue.line}] ${issue.title} (${issue.severity.toUpperCase()})
- **Category:** ${issue.category}
- **Description:** ${issue.description}
- **Recommendation:** ${issue.recommendation}
\`\`\`
${issue.codeSnippet || ''}
\`\`\`
`).join('\n')}

---

## ✨ Suggested Refactored Code

\`\`\`
${reviewData.refactoredCode || '// No refactored code available'}
\`\`\`

---
*Report generated by CodeGuardian AI Automated Code Reviewer*
`;
  }

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${filename}.${extension}`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
